import { writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const VERSION = '00fd7079c3890f430759536f91aa5e854ec0ca4f';
const SOURCE = `https://raw.githubusercontent.com/davidluzgouveia/kanji-data/${VERSION}/kanji.json`;
const OUT = join(resolve(import.meta.dirname, '..'), 'src', 'kanji-data.ts');

interface Entry {
  strokes: number;
  freq: number | null;
  jlpt_new: number | null;
  meanings: string[];
  readings_on: string[];
  readings_kun: string[];
}

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`HTTP ${response.status}`);
const data = (await response.json()) as Record<string, Entry>;

// Kun readings in katakana are old unit names (粉 = デシメートル) and readings ending in っ only occur inside
// compounds (学 = がっ), so neither is worth practising on its own.
const clean = (readings: string[]) =>
  [
    ...new Set(
      readings
        .filter(reading => /^[ぁ-ゖ.-]+$/.test(reading) && !reading.endsWith('っ'))
        .map(reading => reading.replace(/-/g, '')),
    ),
  ].join(' ');
const quote = (text: string) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const lines = Object.entries(data)
  .filter((entry): entry is [string, Entry & { jlpt_new: number }] => entry[1].jlpt_new !== null)
  .sort(
    ([, a], [, b]) => b.jlpt_new - a.jlpt_new || (a.freq ?? Infinity) - (b.freq ?? Infinity) || a.strokes - b.strokes,
  )
  .map(([kanji, entry]) => {
    const meanings = entry.meanings.filter(meaning => !meaning.startsWith('(')).join('; ');
    const fields = [
      kanji,
      entry.jlpt_new,
      entry.strokes,
      clean(entry.readings_on),
      clean(entry.readings_kun),
      meanings,
    ];
    return `  [${fields.map(field => (typeof field === 'number' ? field : quote(field))).join(', ')}],`;
  });

await writeFile(
  OUT,
  `// Generated by scripts/fetch-kanji.ts. Do not edit by hand.
// Kanji, readings and meanings: KANJIDIC by the Electronic Dictionary Research and Development Group, CC BY-SA 4.0,
// via kanji-data by David Gouveia (MIT). JLPT levels: Jonathan Waller, tanos.co.uk.
// [kanji, JLPT level, strokes, on readings, kun readings (okurigana after a dot), meanings]
import type { KanjiEntry } from './types.ts';

export const KANJI_DATA: KanjiEntry[] = [
${lines.join('\n')}
];
`,
);

console.log(`Saved ${lines.length} kanji to src/kanji-data.ts`);
