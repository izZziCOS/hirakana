// Writes src/kanji-parts.ts: the parts each JLPT kanji is built from, taken from the KanjiVG stroke files in
// vendor/kanjivg. Run with `node scripts/make-kanji-parts.ts` after refreshing those files or the kanji list.
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { KANJI_DATA } from '../src/kanji-data.ts';
import { kanjivgFile } from '../src/ui/kanjivg.ts';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = join(ROOT, 'src', 'kanji-parts.ts');

// The outermost named groups inside the kanji's own group. A part drawn in two places (kvg:part="1", "2") is listed
// once, and a radical form such as 氵 keeps the kanji it comes from (水) after an "=".
export function partsOf(svg: string, char: string): string[] {
  const code = kanjivgFile(char).replace('.svg', '');
  const start = svg.indexOf(`<g id="kvg:${code}"`);
  if (start === -1) return [];
  const parts: string[] = [];
  const covered: boolean[] = [];
  for (const match of svg.slice(start).matchAll(/<g\b([^>]*)>|<\/g>/g)) {
    if (match[0] === '</g>') {
      covered.pop();
      if (!covered.length) break;
      continue;
    }
    const attributes = match[1] ?? '';
    if (!covered.length) {
      covered.push(false);
      continue;
    }
    const element = /kvg:element="([^"]+)"/.exec(attributes)?.[1];
    const original = /kvg:original="([^"]+)"/.exec(attributes)?.[1];
    const parentCovered = covered.at(-1) ?? false;
    if (!parentCovered && element && element !== char) {
      parts.push(original && original !== element ? `${element}=${original}` : element);
    }
    covered.push(parentCovered || Boolean(element));
  }
  return [...new Set(parts)];
}

async function main(): Promise<void> {
  const entries: string[] = [];
  for (const [char] of KANJI_DATA) {
    const svg = await readFile(join(ROOT, 'vendor', 'kanjivg', kanjivgFile(char)), 'utf8').catch(() => '');
    const parts = partsOf(svg, char);
    if (parts.length) entries.push(`  ${char}: '${parts.join(' ')}',`);
  }
  await writeFile(
    OUT,
    `// Generated by scripts/make-kanji-parts.ts. Do not edit by hand.
// Derived from KanjiVG (https://kanjivg.tagaini.net) by Ulrich Apel, CC BY-SA 3.0.
// Each kanji's parts, separated by spaces; "氵=水" is a radical form and the kanji it comes from.
export const KANJI_PARTS: Record<string, string> = {
${entries.join('\n')}
};
`,
  );
  console.log(`Wrote ${entries.length} kanji to ${OUT}`);
}

if (import.meta.main) await main();
